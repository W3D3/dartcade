// Writes shared/coach/landing/level-N.gen.ts for every bot level 1–10: where a dart aimed at each of
// the coach's aims lands for a player of that level, from 40,000 darts per aim thrown with the bots'
// own model (bots/accuracy.ts throwAt, jitter included). One file per level, so the browser loads
// only the one it coaches with. Seeded per level, so a rerun gives the same files.
// Run: npm run gen:coach (then npm run format at the repo root).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { throwAt } from '../bots/accuracy.js'
import { sigmaForLevel } from '../bots/levels.js'
import { LEVEL_AVERAGE } from '../shared/botLevels.js'
import { seededRng } from '../shared/rng.js'
import { AIMS, type Outcome } from '../shared/coach/aims.js'
import { dartPoints, isDoubleDart } from '../shared/coach/walk.js'

const THROWS = 40_000
const MIN_P = 0.001

for (let level = 1; level <= LEVEL_AVERAGE.length; level++) {
  const sigma = sigmaForLevel(level)
  const rng = seededRng(1)

  const table: Outcome[][] = AIMS.map(aim => {
    const counts = new Map<string, { points: number; double: boolean; n: number }>()
    for (let i = 0; i < THROWS; i++) {
      const { segment: s } = throwAt(aim, sigma, rng)
      const name = s.multiplier === 0 ? 'Miss' : s.name
      const c = counts.get(name) ?? { points: dartPoints({ segment: s }), double: isDoubleDart({ segment: s }), n: 0 }
      c.n++
      counts.set(name, c)
    }
    return [...counts]
      .map(([name, c]): Outcome => [name, c.points, c.double, Math.round((c.n / THROWS) * 1e5) / 1e5])
      .filter(o => o[3] >= MIN_P)
      .sort((a, b) => b[3] - a[3])
  })

  const out = `// Generated by \`npm run gen:coach\` (src/coach/genLanding.ts) from the bots' throw model. Don't edit.
import type { Outcome } from '../aims.js'

/** Per aim (AIMS order): where a dart a level ${level} player (${LEVEL_AVERAGE[level - 1]} average) throws at it lands, likeliest first. */
export const LANDING: readonly (readonly Outcome[])[] = ${JSON.stringify(table)}
`
  writeFileSync(fileURLToPath(new URL(`../shared/coach/landing/level-${level}.gen.ts`, import.meta.url)), out)
  console.log(`level ${level}: wrote ${table.length} aims, ${table.reduce((s, t) => s + t.length, 0)} outcomes`)
}
