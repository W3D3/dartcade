// Writes shared/coach/landing/<tier>.gen.ts for every coaching tier (shared/coach/tiers.ts): where a
// dart aimed at each of the coach's aims lands for a player of that tier's average, from 40,000 darts
// per aim thrown with the bots' own model (bots/accuracy.ts throwAt, jitter included) at the sigma
// for that average (botLevels.ts sigmaForAverage). One file per tier, so the browser loads only the
// one it coaches with. Seeded, so a rerun gives the same files.
// Run: npm run gen:coach (then npm run format at the repo root).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { throwAt } from '../bots/accuracy.js'
import { sigmaForAverage } from '../shared/botLevels.js'
import { seededRng } from '../shared/rng.js'
import { AIMS, type Outcome } from '../shared/coach/aims.js'
import { COACH_TIERS } from '../shared/coach/tiers.js'
import { dartPoints, isDoubleDart } from '../shared/coach/walk.js'

const THROWS = 40_000
const MIN_P = 0.001

for (const tier of COACH_TIERS) {
  const sigma = sigmaForAverage(tier.average)
  const rng = seededRng(1)

  const table: Outcome[][] = AIMS.map(aim => {
    const counts = new Map<string, { points: number; double: boolean; n: number }>()
    for (let i = 0; i < THROWS; i++) {
      const { segment: s } = throwAt(aim, sigma, rng)
      const name = s.multiplier === 0 ? 'Miss' : s.name
      const c = counts.get(name) ?? { points: dartPoints({ segment: s }), double: isDoubleDart({ segment: s }), n: 0 }
      c.n++
      counts.set(name, c)
    }
    return [...counts]
      .map(([name, c]): Outcome => [name, c.points, c.double, Math.round((c.n / THROWS) * 1e5) / 1e5])
      .filter(o => o[3] >= MIN_P)
      .sort((a, b) => b[3] - a[3])
  })

  const out = `// Generated by \`npm run gen:coach\` (src/coach/genLanding.ts) from the bots' throw model. Don't edit.
import type { Outcome } from '../aims.js'

/** Per aim (AIMS order): where a dart ${tier.as} (${tier.average} average) throws at it lands, likeliest first. */
export const LANDING: readonly (readonly Outcome[])[] = ${JSON.stringify(table)}
`
  writeFileSync(fileURLToPath(new URL(`../shared/coach/landing/${tier.id}.gen.ts`, import.meta.url)), out)
  console.log(`${tier.id}: wrote ${table.length} aims, ${table.reduce((s, t) => s + t.length, 0)} outcomes`)
}
